        try:
            resp = self.session.post("https://api.openai.com/v1/responses", json=body, timeout=timeout)
            resp.raise_for_status()
            data = resp.json()
            u = data.get("usage", {}) or {}
            cached = (u.get("input_tokens_details") or {}).get("cached_tokens", 0)
            self.last_job = log_ai_call("openai", self.model, True, int((time.time() - started) * 1000),
                        {"input": max(0, u.get("input_tokens", 0) - cached), "output": u.get("output_tokens", 0), "cached": cached})
        except Exception as e:
            log_ai_call("openai", self.model, False, int((time.time() - started) * 1000), error=str(e))
            raise
        text = data.get("output_text") or "".join(
            c.get("text", "") for item in data.get("output", []) if item.get("type") == "message"
            for c in item.get("content", []) if c.get("type") == "output_text")
        text = (text or "").strip()
        if not text:
            raise ValueError(f"no text in reply (status {data.get('status')}, model {data.get('model')})")
        return text



