def load_config(config_path: str) -> Dict:
    try:
        with open(config_path, "r", encoding="utf-8") as f:
            cfg = yaml.safe_load(f) or {}
    except FileNotFoundError:
        print(f"Config not found: {config_path}", file=sys.stderr)
        sys.exit(1)

    # Convert publishers dict → list for EraDetector
    publishers_list = []
    for key, pub in (cfg.get("publishers") or {}).items():
        publishers_list.append({
            "publisher": pub.get("display_name", key.replace("_", " ").title()),
            "use_folder_detection": pub.get("use_folder_detection", False),
            "eras": pub.get("eras", []),
            "imprints": pub.get("imprints", []),
            "skip_patterns": pub.get("skip_patterns", []),
        })
    cfg["publishers_list"] = publishers_list
    return cfg


