def main():
    parser = argparse.ArgumentParser(description="Omnibus Series Enricher")
    sub = parser.add_subparsers(dest="cmd")

    p = sub.add_parser("create", help="Create series.json from CV ID and enrich")
    p.add_argument("folder_path")
    p.add_argument("cv_volume_id", type=int)
    p.add_argument("--context-folder", default=None)
    p.add_argument("--config", default=None)

    p = sub.add_parser("enrich", help="Enrich existing series.json")
    p.add_argument("folder_path")
    p.add_argument("--config", default=None)
    p.add_argument("--force", action="store_true")
    p.add_argument("--dry-run", action="store_true")
    p.add_argument("--recursive", "-r", action="store_true")

    p = sub.add_parser("retag-genres", help="Genres only, for the series listed in a JSON file [{id, path}]")
    p.add_argument("targets")
    p.add_argument("--config", default=None)
    p.add_argument("--batch", type=int, default=20)

    p = sub.add_parser("revert", help="Revert series.json to backup")
    p.add_argument("folder_path")
    p.add_argument("--recursive", "-r", action="store_true")

    args = parser.parse_args()
    if not args.cmd:
        parser.print_help()
        return

    if args.cmd == "revert":
        p_obj = SeriesJsonParser()
        if getattr(args, "recursive", False):
            count = sum(1 for root, _, files in os.walk(args.folder_path)
                       if "series.json" in files
                       and p_obj.revert(os.path.join(root, "series.json")))
            print(f"Reverted {count} files")
        else:
            p_obj.revert(os.path.join(args.folder_path, "series.json"))
        return

    config_path = getattr(args, "config", None) or os.path.join(os.path.dirname(__file__), "config.yaml")
    cfg = load_config(config_path)
    global AI_RUN_ID
    AI_RUN_ID = (cfg.get("ai_run") or {}).get("id")
    use_genre_config(cfg)
    enricher = SeriesEnricher(cfg)

    if args.cmd == "retag-genres":
        enricher.retag_genres(args.targets, batch=max(1, min(args.batch, 40)))
        return

    if args.cmd == "create":
        enricher.create(args.folder_path, args.cv_volume_id, context_folder=args.context_folder)

    elif args.cmd == "enrich":
        if getattr(args, "recursive", False):
            total, enriched = enricher.enrich_directory(
                args.folder_path, recursive=True,
                dry_run=getattr(args, "dry_run", False),
                force=getattr(args, "force", False),
            )
            print(f"\nSummary: {enriched}/{total} enriched")
        else:
            enricher.enrich(
                args.folder_path,
                force=getattr(args, "force", False),
                dry_run=getattr(args, "dry_run", False),
            )


if __name__ == "__main__":
    main()
