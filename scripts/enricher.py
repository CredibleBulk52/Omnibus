class SeriesEnricher:
    def __init__(self, config: Dict):
        self.config = config
        self.parser = SeriesJsonParser()
        self.era_detector = EraDetector(config.get("publishers_list", []))
        self._cv = None
        self._ai = None

    @property
    def cv(self) -> Optional[ComicVineClient]:
        if self._cv is None:
            # Either source alone works (an install may have only one): Comic Vine only, Metron
            # only (series known to Metron by their Comic Vine ID), or both (Metron first).
            keys = self.config.get("api_keys", {})
            key = keys.get("comicvine") or ""
            metron_token = keys.get("metron") or ""
            if key or metron_token:
                self._cv = ComicVineClient(key, MetronClient(metron_token) if metron_token else None)
        return self._cv

    @property
    def ai(self) -> Optional[AnthropicClient]:
        # The model comes from Settings -> AI Models (Enricher task); an
        # "openai:" prefix routes it to OpenAI with the OpenAI key.
        if self._ai is None:
            model = self.config.get("anthropic", {}).get("model", "claude-haiku-5-5")
            keys = self.config.get("api_keys", {})
            if model.startswith("openai:"):
                if keys.get("openai"):
                    self._ai = OpenAIClient(keys["openai"], model.split(":", 1)[1])
            elif keys.get("anthropic"):
                self._ai = AnthropicClient(keys["anthropic"], model)
        return self._ai

    def create(self, folder_path: str, cv_volume_id: int, context_folder: str = None) -> bool:
        """Fetch CV data, write series.json, then enrich. Prints JSON result to stdout."""
        if not self.cv:
            print(json.dumps({"error": "No Comic Vine API key or Metron token configured (Settings → Connections)"}))
            return False

        print(f"[create] Fetching volume {cv_volume_id}...", file=sys.stderr)
        vol = self.cv.get_volume(cv_volume_id)
        if not vol:
            why = ("Metron does not know this Comic Vine series" if not self.cv.api_key
                   else "Comic Vine is at its hourly limit and Metron does not know this series; try again later" if getattr(self.cv, "limited", False)
                   else f"Could not fetch Comic Vine volume {cv_volume_id}")
            print(json.dumps({"error": why}))
            return False

        os.makedirs(folder_path, exist_ok=True)
        json_path = os.path.join(folder_path, "series.json")

        pub_lower = (vol.get("publisher") or "").lower()
        reading_direction = "rtl" if pub_lower in MANGA_PUBLISHERS else None

        series = SeriesJson()
        series.metadata = SeriesMetadata(
            type="comicSeries",
            publisher=vol.get("publisher"),
            name=vol.get("name"),
            comicid=vol.get("id"),
            year=vol.get("year"),
            volume=vol.get("year"),
            imprint=vol.get("imprint"),
            description_text=vol.get("description", ""),
            description_formatted=vol.get("description", ""),
            booktype=vol.get("booktype") or "Print",
            comic_image=vol.get("image"),
            total_issues=vol.get("issue_count"),
            publication_run=vol.get("publication_run"),
            # Unknown run (dates skipped at Comic Vine's limit): leave status empty rather than guess "Continuing".
            status=vol.get("status") or (derive_status(vol.get("publication_run")) if vol.get("publication_run") else None),
            characters=vol.get("characters") or [],
            genres=vol.get("cv_genres") or [],
            reading_direction=reading_direction,
        )

        self.parser.write(json_path, series)

        # Enrich the newly created file
        self.enrich(folder_path, force=False, _quiet=True, context_folder=context_folder)

        final = self.parser.read(json_path)
        name = (final.metadata.name if final else None) or vol.get("name")
        print(json.dumps({"success": True, "path": json_path, "name": name, "comicid": vol.get("id")}))
        return True

    def enrich(self, folder_path: str, force: bool = False, dry_run: bool = False, _quiet: bool = False, context_folder: str = None) -> bool:
        json_path = os.path.join(folder_path, "series.json")
        if not os.path.exists(json_path):
            print(f"  No series.json at {json_path}", file=sys.stderr)
            return False

        series = self.parser.read(json_path)
        if not series:
            return False

        if not _quiet:
            print(f"\n{'[DRY RUN] ' if dry_run else ''}Processing: {os.path.basename(folder_path)}")

        # Skip recently enriched
        skip_days = self.config.get("enrichment", {}).get("skip_if_enriched_within_days", 30)
        if not force and series.metadata.enrichment and skip_days > 0:
            enrich_date = series.metadata.enrichment.get("date")
            if enrich_date:
                try:
                    if datetime.fromisoformat(enrich_date) > datetime.now() - timedelta(days=skip_days):
                        if not _quiet:
                            print("  Skipping (recently enriched)")
                        return False
                except Exception:
                    pass

        sources = []

        # Era + imprint
        _, era, imprint, skip = self.era_detector.detect(context_folder or folder_path, series.metadata.year)
        if skip:
            if not _quiet:
                print("  Skipping (skip pattern matched)")
            return False

        if era and series.metadata.era != era:
            print(f"  Era: {era}")
            series.metadata.era = era
        if imprint and series.metadata.imprint != imprint:
            print(f"  Imprint: {imprint}")
            series.metadata.imprint = imprint

        # Comic Vine
        cv_vol = None
        if self.cv and series.metadata.comicid:
            cv_vol = self.cv.get_volume(series.metadata.comicid)
            if cv_vol:
                sources.extend(cv_vol.get("sources") or ["comicvine"])

                if cv_vol.get("characters") and (force or not series.metadata.characters):
                    series.metadata.characters = cv_vol["characters"]
                    print(f"  Characters ({len(cv_vol['characters'])}): {cv_vol['characters']}")

                if cv_vol.get("booktype") and series.metadata.booktype in (None, "", "Print") and cv_vol["booktype"] != "Print":
                    print(f"  Book type: {cv_vol['booktype']}")
                    series.metadata.booktype = cv_vol["booktype"]

                if cv_vol.get("publication_run"):
                    new_status = cv_vol.get("status") or derive_status(cv_vol["publication_run"])
                    if series.metadata.status != new_status:
                        print(f"  Status: {new_status}")
                        series.metadata.status = new_status
                    if series.metadata.publication_run != cv_vol["publication_run"]:
                        print(f"  Publication run: {cv_vol['publication_run']}")
                        series.metadata.publication_run = cv_vol["publication_run"]

                if cv_vol.get("issue_count") is not None and series.metadata.total_issues != cv_vol["issue_count"]:
                    print(f"  Total issues: {series.metadata.total_issues} -> {cv_vol['issue_count']}")
                    series.metadata.total_issues = cv_vol["issue_count"]

                if cv_vol.get("year") and not series.metadata.year:
                    print(f"  Year: {cv_vol['year']}")
                    series.metadata.year = cv_vol["year"]
                if cv_vol.get("year") and not series.metadata.volume:
                    series.metadata.volume = cv_vol["year"]

                if cv_vol.get("image") and not series.metadata.comic_image:
                    series.metadata.comic_image = cv_vol["image"]

                if cv_vol.get("publisher") and not series.metadata.publisher:
                    series.metadata.publisher = cv_vol["publisher"]

                # Reading direction from publisher
                pub_lower = (series.metadata.publisher or "").lower()
                if pub_lower in MANGA_PUBLISHERS and not series.metadata.reading_direction:
                    series.metadata.reading_direction = "rtl"
                    print(f"  Reading direction: rtl (manga publisher)")

                # CV genre fallback when no AI
                if cv_vol.get("cv_genres") and not self.ai and (force or not series.metadata.genres):
                    series.metadata.genres = cv_vol["cv_genres"]
                    print(f"  Genres (CV): {cv_vol['cv_genres']}")

        # AI description
        force_desc = self.config.get("enrichment", {}).get("force_description", False)
        lib_sources, creators = library_sources([folder_path, context_folder])
        if self.ai and (force_desc or force or AnthropicClient.is_inadequate(series.metadata.description_text)):
            # Sources, best first: the publisher's solicitations in the library's own files, then
            # Comic Vine's series description; Comic Vine's issue descriptions only when the files
            # have none. (Until 2026-10-28 issue text was fetched only if the AI said UNKNOWN,
            # which it never does for a famous character, so new series were written from memory.)
            desc_sources = list(lib_sources)
            if cv_vol and cv_vol.get("description") and len(cv_vol["description"]) > 50:
                desc_sources.append(("Comic Vine series description", cv_vol["description"]))
            # Only when Comic Vine can answer now: this optional extra must not wait out its hourly limit.
            if not lib_sources and self.cv and series.metadata.comicid and self.cv.api_key \
                    and self.cv.pool.available("volume") and self.cv.pool.available("issue"):
                issues = self.cv.get_issues(series.metadata.comicid)
                if issues:
                    print(f"  [Claude] No solicitations in the files; fetching Comic Vine issue descriptions...")
                    for line in self.cv.get_issue_descriptions(issues):
                        label, _, text = line.partition(": ")
                        desc_sources.append((f"{label} (Comic Vine)", text))
            names = [n for n, _ in desc_sources]
            print(f"  [Claude] Generating description from {len(desc_sources)} source(s)"
                  + (f": {', '.join(names)}" if names else " (none: from the model's own knowledge)") + "...")
            desc = self.ai.generate_description(series.metadata, desc_sources or None, creators or None)

            if desc and desc != "UNKNOWN":
                sources.append("ai")
                series.metadata.description_text = desc
                series.metadata.description_formatted = desc
                print(f"  Description: {desc[:80]}...")

        # AI genres
        previous = series.metadata.enrichment if isinstance(series.metadata.enrichment, dict) else {}
        genres_version = previous.get("genres_version")
        if self.ai and (force or not series.metadata.genres):
            genres = self.ai.classify_genre(series.metadata, lib_sources[0][1] if lib_sources else None)
            if genres:
                sources.append("ai_genre")
                series.metadata.genres = genres
                genres_version = GENRE_VERSION or genres_version
                print(f"  Genres (AI): {genres}")

        # Mark enriched. genres_version: the genre list the genres were chosen from
        # (Library > Genres retags series that are on an older list).
        if sources:
            series.metadata.enrichment = {
                "source": "+".join(sorted(set(sources))),
                "date": datetime.now().isoformat(),
                "version": "1.0",
                **({"genres_version": genres_version} if genres_version else {}),
            }

        if not dry_run and sources:
            if self.parser.write(json_path, series):
                if not _quiet:
                    print(f"  ✓ Enriched: {', '.join(sorted(set(sources)))}")
                return True
        elif dry_run and sources:
            print(f"  Would enrich: {', '.join(sorted(set(sources)))}")
            return True
        else:
            if not _quiet:
                print("  No enrichment needed")

        return False

    def retag_genres(self, targets_path: str, batch: int = 20) -> None:
        """Genres only, for many series (Library > Genres, 2026-11-03). Uses what each
        series.json already holds (no Comic Vine) and asks the AI about `batch` series per
        call. Writes nothing: prints one JSON line per series ("result": answered with the
        allowed genres, up to GENRE_LIMIT, or no_answer) and per batch ("progress"), and the
        server writes each series.json under the library's lock for that series."""
        def emit(kind, data):
            print(json.dumps({kind: data}, ensure_ascii=False), flush=True)
        with open(targets_path, encoding="utf-8") as f:
            targets = json.load(f)
        if not self.ai:
            emit("fatal", "No AI key for the Enricher task (Settings > AI Models)")
            return
        items = []
        for t in targets:
            try:
                with open(os.path.join(t["path"], "series.json"), encoding="utf-8") as f:
                    data = json.load(f)
            except Exception as e:
                emit("result", {"id": t["id"], "status": "unreadable", "error": str(e)[:200]})
                continue
            if not isinstance(data, dict) or not isinstance(data.get("metadata"), dict):
                emit("result", {"id": t["id"], "status": "unusual"})
                continue
            items.append((t, data["metadata"]))
        total = len(items)
        emit("progress", {"done": 0, "total": total})
        for i in range(0, total, batch):
            chunk = items[i:i + batch]
            self.ai.problem = None
            answers = self.ai.genres_for_many([m for _, m in chunk])
            if self.ai.problem:
                emit("warning", self.ai.problem[:300])
            for (t, meta), genres in zip(chunk, answers):
                before = meta.get("genres") if isinstance(meta.get("genres"), list) else []
                emit("result", {"id": t["id"], "status": "answered" if genres else "no_answer", "before": before, "after": genres})
            emit("progress", {"done": min(i + batch, total), "total": total})

    def enrich_directory(self, directory: str, recursive: bool, dry_run: bool, force: bool = False) -> Tuple[int, int]:
        series_files = []
        for root, _, files in os.walk(directory):
            if "series.json" in files:
                series_files.append(os.path.join(root, "series.json"))
            if not recursive:
                break
        print(f"Found {len(series_files)} series.json files")
        enriched = sum(1 for p in series_files if self.enrich(os.path.dirname(p), force=force, dry_run=dry_run))
        return len(series_files), enriched


