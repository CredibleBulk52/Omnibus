class ComicVineClient:
    BASE_URL = "https://comicvine.gamespot.com/api"

    def __init__(self, api_key: str, metron: Optional[MetronClient] = None):
        self.api_key = api_key
        self.last_request_time = 0
        self.request_delay = 3.0
        self.session = requests.Session()
        self.session.headers.update({"User-Agent": "Omnibus/1.0"})
        self.pool = CvPool()
        self.metron = metron
        if metron is not None and metron.conn is None:
            metron.conn = self.pool.conn
        self._volumes: Dict[str, Optional[Dict]] = {}   # create, then enrich, ask for the same volume

    def _rate_limit(self):
        elapsed = time.time() - self.last_request_time
        if elapsed < self.request_delay:
            time.sleep(self.request_delay - elapsed)
        self.last_request_time = time.time()

    def _request(self, endpoint: str, params: Dict, retry: int = 0) -> Optional[Any]:
        if not self.api_key:   # Metron-only install: no Comic Vine key
            return None
        self._rate_limit()
        params.update({"api_key": self.api_key, "format": "json"})
        resource = CvPool.resource_of(endpoint)
        try:
            row_id = self.pool.acquire(resource)   # shared hourly budget + spacing
        except Exception as e:
            print(f"  [CV] {e}", file=sys.stderr)
            return None
        started = int(time.time() * 1000)
        try:
            resp = self.session.get(f"{self.BASE_URL}/{endpoint}", params=params, timeout=30)
            if resp.status_code in (420, 429):
                # Refused: pause this resource for everyone, then retry once the
                # pool allows it (acquire waits out the pause).
                self.pool.finish(row_id, "refused", started)
                self.pool.refused(resource, f"HTTP {resp.status_code}")
                if retry < 2:
                    return self._request(endpoint, params, retry + 1)
                return None
            data = resp.json() if resp.ok else None
            if data and data.get("status_code") == 107:
                self.pool.finish(row_id, "refused", started)
                self.pool.refused(resource, "status_code 107")
                if retry < 2:
                    return self._request(endpoint, params, retry + 1)
                return None
            self.pool.finish(row_id, resp.status_code, started)
            resp.raise_for_status()
            return data.get("results") if data.get("status_code") == 1 else None
        except Exception as e:
            self.pool.finish(row_id, "error", started)
            print(f"  [CV] Error: {e}", file=sys.stderr)
            return None

    def get_volume(self, volume_id: int) -> Optional[Dict]:
        key = str(volume_id)
        if key not in self._volumes:
            self._volumes[key] = self._get_volume(volume_id)
        return self._volumes[key]

    def _get_volume(self, volume_id: int) -> Optional[Dict]:
        # Metron first (own allowance); then one Comic Vine volume request. With Metron's issue
        # dates, Comic Vine's first/last issue lookups are skipped. When Comic Vine's volume
        # allowance is used up or paused, Metron's facts are used alone (characters come later).
        m = None
        if self.metron:
            try:
                m = self.metron.series_facts(volume_id)
            except Exception as e:
                print(f"  [Metron] {e}", file=sys.stderr)
            if m:
                print(f"  [Metron] series {m['metron_id']}: {m.get('status') or '?'} · {m.get('booktype') or '?'} · "
                      f"{m.get('first') or '?'} – {m.get('last') or '?'}", file=sys.stderr)
        if m and not self.api_key:
            return self._from_metron(volume_id, m)
        if m and not self.pool.available("volume"):
            print("  [CV] volume allowance used up — using Metron's details now; characters on a later enrich", file=sys.stderr)
            return self._from_metron(volume_id, m)
        if not self.api_key:
            return None
        if self.metron and not m and not self.pool.available("volume"):
            # With Metron set up, don't wait out Comic Vine's hour for a series Metron doesn't know.
            print("  [CV] volume allowance used up and Metron does not know this series", file=sys.stderr)
            self.limited = True
            return None
        fields = "id,name,start_year,publisher,count_of_issues,image,description,characters,concepts"
        if not (m and m.get("first")):
            fields += ",first_issue,last_issue"
        result = self._request(f"volume/4050-{volume_id}", {"field_list": fields})
        if not result:
            return self._from_metron(volume_id, m) if m else None
        if m and m.get("first"):
            return self._merge(result, m)

        # Publication run
        pub_run = None
        fi = result.get("first_issue") or {}
        li = result.get("last_issue") or {}
        # Issue dates need the single-issue allowance; with Metron set up, skip them rather than wait.
        dates_ok = not self.metron or self.pool.available("issue")
        fd = self._issue_date(fi.get("id")) if dates_ok else None
        # A one-shot's first and last issue are the same issue: its run is that one month.
        # (Before 2026-11-12 an equal first and last date fell through to "- Present".)
        same = bool(li) and li.get("id") == fi.get("id")
        ld = fd if same else (self._issue_date(li.get("id")) if li and dates_ok else None)
        if fd and ld and fd != ld:
            pub_run = f"{fd} - {ld}"
        elif fd and ld:
            pub_run = fd
        elif fd:
            pub_run = f"{fd} - Present"
        # A continuing series shows "Present" as its end, matching the server's
        # scheduled series.json refresh (avoids the two flip-flopping the value).
        if pub_run and "Present" not in pub_run and derive_status(pub_run) == "Continuing":
            pub_run = pub_run.split(" - ")[0] + " - Present"

        # Clean description
        description = None
        if result.get("description"):
            description = re.sub(r'<[^>]+>', '', result["description"])
            description = re.sub(r'\s+', ' ', description).strip()

        # Characters (top 10)
        characters = [c.get("name") for c in (result.get("characters") or []) if c.get("name")][:10]

        # CV genres from concepts
        VALID_GENRES = set(GENRES)
        cv_genres = [c.get("name") for c in (result.get("concepts") or [])
                     if c.get("name") in VALID_GENRES]

        vol = {
            "id": result.get("id"),
            "name": result.get("name"),
            "year": int(result["start_year"]) if result.get("start_year") else None,
            "publisher": (result.get("publisher") or {}).get("name"),
            "issue_count": result.get("count_of_issues", 0),
            "image": (result.get("image") or {}).get("medium_url"),
            "description": description,
            "publication_run": pub_run,
            "characters": characters,
            "cv_genres": cv_genres,
            "sources": ["comicvine"],
        }
        if m:   # Metron knew the series but had no issue dates: still take its status and book type
            vol.update({"imprint": m.get("imprint"), "booktype": m.get("booktype"), "sources": ["comicvine", "metron"]})
            if m.get("status"):
                vol["status"] = m["status"]
                if pub_run:
                    end = pub_run.split(" - ")[-1] if " - " in pub_run else pub_run
                    vol["publication_run"] = publication_run(pub_run.split(" - ")[0], None if end == "Present" else end, m["status"])
        return vol

    @staticmethod
    def _clean_desc(text: Optional[str]) -> Optional[str]:
        if not text:
            return None
        return re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', text)).strip() or None

    def _merge(self, result: Dict, m: Dict) -> Dict:
        """Comic Vine's volume plus Metron's status, book type, run and (if missing) cover."""
        status = m.get("status")
        run = publication_run(m.get("first"), m.get("last"), status)
        VALID_GENRES = set(GENRES)
        return {
            "id": result.get("id"),
            "name": result.get("name") or m.get("name"),
            "year": int(result["start_year"]) if result.get("start_year") else m.get("year"),
            "publisher": (result.get("publisher") or {}).get("name") or m.get("publisher"),
            "imprint": m.get("imprint"),
            "issue_count": result.get("count_of_issues", m.get("issue_count") or 0),
            "image": (result.get("image") or {}).get("medium_url") or m.get("image"),
            "description": self._clean_desc(result.get("description")) or m.get("description"),
            "publication_run": run,
            "status": status or (derive_status(run) if run else None),
            "booktype": m.get("booktype"),
            "characters": [c.get("name") for c in (result.get("characters") or []) if c.get("name")][:10],
            "cv_genres": [c.get("name") for c in (result.get("concepts") or []) if c.get("name") in VALID_GENRES],
            "sources": ["comicvine", "metron"],
        }

    def _from_metron(self, volume_id, m: Dict) -> Dict:
        """Metron alone (Comic Vine's volume allowance used up, or its request failed)."""
        status = m.get("status")
        run = publication_run(m.get("first"), m.get("last"), status)
        return {
            "id": int(volume_id),
            "name": m.get("name"),
            "year": m.get("year"),
            "publisher": m.get("publisher"),
            "imprint": m.get("imprint"),
            "issue_count": m.get("issue_count") or 0,
            "image": m.get("image"),
            "description": m.get("description"),
            "publication_run": run,
            "status": status or (derive_status(run) if run else None),
            "booktype": m.get("booktype"),
            "characters": [],
            "cv_genres": [],
            "sources": ["metron"],
        }

    def _issue_date(self, issue_id) -> Optional[str]:
        if not issue_id:
            return None
        d = self._request(f"issue/4000-{issue_id}", {"field_list": "cover_date"})
        cd = (d or {}).get("cover_date") if isinstance(d, dict) else None
        if cd:
            try:
                return datetime.strptime(cd, "%Y-%m-%d").strftime("%B %Y")
            except Exception:
                return cd
        return None

    def get_issue_descriptions(self, issues: List[Dict]) -> List[str]:
        if not issues:
            return []
        n = len(issues)
        if n <= 4:
            indices = [0, min(1, n - 1)]
        elif n <= 12:
            indices = [0, 1, n - 1]
        elif n <= 50:
            indices = [0, 1, n // 2, n - 1]
        else:
            indices = [0, 1, n // 4, n * 3 // 4, n - 1]
        indices = sorted(set(i for i in indices if 0 <= i < n))

        descriptions = []
        for idx in indices:
            issue_id = (issues[idx] or {}).get("id")
            if not issue_id:
                continue
            result = self._request(f"issue/4000-{issue_id}", {"field_list": "description,issue_number"})
            if not result or not result.get("description"):
                continue
            desc = re.sub(r'<[^>]+>', '', result["description"])
            desc = re.sub(r'\s+', ' ', desc).strip()
            if len(desc) > 50:
                descriptions.append(f"Issue #{result.get('issue_number', idx+1)}: {desc}")
        return descriptions

    def get_issues(self, volume_id: int) -> List[Dict]:
        result = self._request(f"volume/4050-{volume_id}", {"field_list": "issues"})
        return (result or {}).get("issues") or []


