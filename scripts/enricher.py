# The server's run for this enricher process (config ai_run.id, 2026-11-03): its calls are
# grouped in Settings > AI Models > Usage & results, and the server adds each call's cost,
# "AI call failed" warnings and one "AI run finished" line when the process ends.
AI_RUN_ID: Optional[str] = None


def _ai_db():
    return sqlite3.connect(os.environ.get("DB_PATH", "/appdata/omnibus.db"), timeout=5, isolation_level=None)


def log_ai_call(provider: str, model: str, ok: bool, ms: int, usage: dict = None, error: str = None) -> Optional[str]:
    """Record one enricher AI call (one job) in ai_calls / ai_jobs for Settings -> AI Models -> Usage.
    Returns the job id; never fails the enrichment."""
    try:
        import uuid
        u = usage or {}
        now = int(time.time() * 1000)
        day = time.strftime("%Y-%m-%d", time.gmtime(now / 1000))
        mid = model if provider == "anthropic" else f"openai:{model}"
        job = str(uuid.uuid4())
        conn = _ai_db()
        try:
            conn.execute(
                "INSERT INTO ai_calls (at, day, task, tier, provider, model, source, ok, error, ms, input_tokens, output_tokens, cache_read, cache_write, web_searches, job_id, run_id) "
                "VALUES (?, ?, 'enricher', 'quick', ?, ?, 'live', ?, ?, ?, ?, ?, ?, 0, 0, ?, ?)",
                (now, day, provider, mid, 1 if ok else 0, (error or "")[:300] or None, ms, u.get("input", 0), u.get("output", 0), u.get("cached", 0), job, AI_RUN_ID))
            conn.execute(
                "INSERT INTO ai_jobs (id, at, day, task, tier, provider, model, source, calls, failed_calls, ms) VALUES (?, ?, ?, 'enricher', 'quick', ?, ?, 'live', 1, ?, ?)",
                (job, now, day, provider, mid, 0 if ok else 1, ms))
        finally:
            conn.close()
        return job
    except Exception:
        return None


def set_ai_job_outcome(job: Optional[str], outcome: str, detail: str = None):
    if not job:
        return
    try:
        conn = _ai_db()
        try:
            conn.execute("UPDATE ai_jobs SET outcome = ?, detail = ? WHERE id = ?", (outcome, (detail or "")[:200] or None, job))
        finally:
            conn.close()
    except Exception:
        pass


class AnthropicClient:
    def __init__(self, api_key: str, model: str = "claude-haiku-5-5"):
        self.api_key = api_key
        self.model = model
        self.problem = None   # last genre-batch problem, reported by retag-genres
        self.session = requests.Session()
        self.session.headers.update({
            "x-api-key": api_key,
            "anthropic-version": "2023-06-01",
            "Content-Type": "application/json",
        })

    @staticmethod
    def _text(resp) -> str:
        # Newer models can return a thinking block before the answer, or use the
        # whole token budget thinking. Join the text blocks; never assume the
        # first block is text.
        data = resp.json()
        AnthropicClient.last_stop = data.get("stop_reason")
        text = "".join(b.get("text", "") for b in data.get("content", []) if b.get("type") == "text").strip()
        if not text:
            raise ValueError(f"no text in reply (stop_reason {data.get('stop_reason')}, model {data.get('model')})")
        return text

    def _ask(self, user: str, system: Optional[str] = None, max_tokens: int = 2048, timeout: int = 60,
             thinking_off: bool = False) -> str:
        # thinking_off: newer Claude models think by default and the thinking counts against
        # max_tokens; a short answer (genres) can be all thinking and no text (2026-11-03: Haiku 5.5
        # returned no genres for a whole test retag). Same as aiClient.js `thinking: 'off'`.
        body = {"model": self.model, "max_tokens": max_tokens, "messages": [{"role": "user", "content": user}]}
        if system:
            body["system"] = system
        if thinking_off:
            body["thinking"] = {"type": "disabled"}
        started = time.time()
        try:
            resp = self.session.post("https://api.anthropic.com/v1/messages", json=body, timeout=timeout)
            if resp.status_code == 400 and thinking_off and "thinking" in (resp.text or "").lower():
                body.pop("thinking", None)   # a model that does not take the setting: ask without it,
                body["max_tokens"] = max_tokens + 6000   # with room for its thinking (2026-11-04: Sonnet retag cut off)
                resp = self.session.post("https://api.anthropic.com/v1/messages", json=body, timeout=timeout)
            resp.raise_for_status()
            u = resp.json().get("usage", {}) or {}
            self.last_job = log_ai_call("anthropic", self.model, True, int((time.time() - started) * 1000),
                        {"input": u.get("input_tokens", 0), "output": u.get("output_tokens", 0), "cached": u.get("cache_read_input_tokens", 0)})
        except Exception as e:
            log_ai_call("anthropic", self.model, False, int((time.time() - started) * 1000), error=str(e))
            raise
        return self._text(resp)

    def generate_description(self, meta: SeriesMetadata, sources: List[Tuple[str, str]] = None,
                             creators: Dict[str, str] = None) -> Optional[str]:
        # A hook for the series (user 2026-10-28: concept and intention, not a plot summary), written
        # from the reference material, not from memory; the old "punchy, vivid" brief produced hype
        # and invented details for new series.
        system = """You write the pitch on a comic library's series page: a short hook that makes a reader want to start this series. It is not a plot summary.
Capture the series' concept and intention: what makes this take distinctive, who it follows, and the tension or stakes that drive it, in the series' own tone.
Solicitation taglines are often the best statement of the concept: "Without the mentor... without the family... without the Speed Force, what's left is the Absolute Scarlet Speedster!" means this version of the hero exists without those things. Use that idea in your own words; do not read a tagline as something that happened, and do not turn teaser questions ("Can he escape?") into events or outcomes.
Write 3 sentences, about 50-80 words, in present tense. Do not recount events, list places, villains or story arcs, or narrate in sequence ("then", "eventually"). The later issues are there only to show the series' tone and scope.
{ACCURACY}
No spoilers: no deaths, twists, secret identities or endings.
Avoid hype and stock phrases such as "pulse-pounding", "heart-stopping", "edge of your seat", "thrilling ride", "redefines", "like never before", "epic saga", "unforgettable", "buckle up", "fastest man alive". Never start with "Dive into", "Step into", "Welcome to" or "Join". Never copy the solicitation's all-caps headlines.
If no reference material is provided and you do not know this specific series, respond with: UNKNOWN
Write only the pitch (or UNKNOWN), no preamble or quotes."""

        # Established series (user 2026-10-28): the AI knows older runs better than their old
        # solicitation text does, so it may use what it reliably knows; recent series, which it may
        # not know, are written from the references only.
        try:
            established = bool(meta.year) and int(meta.year) < RECENT_SERIES_FROM
        except (TypeError, ValueError):
            established = False
        system = system.replace("{ACCURACY}", ACCURACY_ESTABLISHED if established else ACCURACY_RECENT)
        user = f"Series: {meta.name}\nPublisher: {meta.publisher}\nStarted: {meta.year}"
        if getattr(meta, "imprint", None):
            user += f"\nImprint / line: {meta.imprint}"
        if creators:
            user += "\nCreators: " + ", ".join(f"{v} ({k})" for k, v in creators.items())
        if sources:
            user += "\n\nReference material (the only source of facts):"
            for name, desc in sources:
                user += f"\n[{name}]: {desc[:900]}"
        else:
            user += f"\nCharacters (from Comic Vine, unranked): {', '.join((meta.characters or [])[:5]) or 'Unknown'}"

        try:
            self.last_job = None
            result = self._ask(user, system=system, max_tokens=2048, timeout=60).strip().strip('"\'')
            if result.strip().upper().rstrip(".") == "UNKNOWN" or (not sources and "UNKNOWN" in result.upper()):
                set_ai_job_outcome(self.last_job, "unknown", "series not recognised")
                return "UNKNOWN"
            set_ai_job_outcome(self.last_job, "written", f"description from {len(sources or [])} sources")
            return result
        except Exception as e:
            print(f"  [Claude] Description error: {e}", file=sys.stderr)
            return None

