# Allowed series genres (2026-11-03). The server sends the list, with a one-line
# definition for each, in the run's config (genres: {version, list}; backend/genres.js
# is the one place it is kept); this copy is only for a run without it.
GENRES = ["Superhero", "Crime", "Horror", "Science Fiction", "Fantasy", "Mystery", "Thriller", "Comedy",
          "Drama", "Romance", "War", "Western", "Noir", "Espionage", "Supernatural", "Cosmic", "Street-Level",
          "Team", "Teen", "Martial Arts", "Post-Apocalyptic", "Alternate Reality", "Anti-Hero", "All-Ages",
          "Sword & Sorcery", "Pulp", "Cyberpunk", "Kaiju", "Historical"]
GENRE_DEFS: Dict[str, str] = {}
GENRE_VERSION: Optional[str] = None
GENRE_LIMIT = 4


def use_genre_config(cfg: Dict) -> None:
    global GENRES, GENRE_DEFS, GENRE_VERSION
    g = cfg.get("genres") or {}
    items = [i for i in (g.get("list") or []) if isinstance(i, dict) and i.get("name")]
    if items:
        GENRES = [i["name"] for i in items]
        GENRE_DEFS = {i["name"]: i.get("definition") or "" for i in items}
    GENRE_VERSION = g.get("version")


def _genre_key(name: str) -> str:
    return re.sub(r"[^a-z]", "", str(name or "").lower().replace("&", "and"))


def allowed_genres(names, limit: Optional[int] = None) -> List[str]:
    """Names on the list only (spelling of hyphens, spaces and '&' ignored), no repeats."""
    by_key = {_genre_key(g): g for g in GENRES}
    out = []
    for n in names if isinstance(names, list) else []:
        g = by_key.get(_genre_key(n))
        if g and g not in out:
            out.append(g)
    return out[:limit or GENRE_LIMIT]


def genre_guide() -> str:
    return "\n".join(f"- {g}: {GENRE_DEFS[g]}" if GENRE_DEFS.get(g) else f"- {g}" for g in GENRES)


def pick_genres(text: str, limit: Optional[int] = None) -> List[str]:
    """Allowed genres from an AI answer. The answer has sometimes argued with itself
    ('"Action" isn't in the list. Correcting: Adventure'), and its commentary was saved
    as genres (2026-11-03, 80 series). Use the last line that is a plain list (short
    items, no sentences) and keep its allowed names; off-list names such as "Action" are
    dropped. No such line gives no genres, and the series is asked again next time."""
    def loose(g):  # "Street-Level" also matches "Street Level"; "Sword & Sorcery" also "Sword and Sorcery"
        return re.escape(g).replace("\\-", "[-\\s]?").replace("\\ \\&\\ ", "\\s*(?:&|and)\\s*").replace("\\ ", "\\s+")
    pattern = re.compile(r"\b(" + "|".join(loose(g) for g in GENRES) + r")\b", re.I)
    for line in reversed([l.strip() for l in (text or "").splitlines() if l.strip()]):
        line = re.sub(r"^\s*genres?\s*:\s*", "", line, flags=re.I).strip().rstrip(".")
        items = [i.strip(" *-") for i in re.split(r"[,;/]", line) if i.strip(" *-")]
        is_list = items and all(len(i.split()) <= 4 and not re.search(r"[:\"'()?!]", i) for i in items)
        found = [m.group(1) for m in pattern.finditer(line)] if is_list else []
        if found:
            return allowed_genres(found, limit)
    return []


def parse_genre_reply(text: str) -> Dict[str, Any]:
    """The {"1": [...], "2": [...]} answer of a genre batch. The model has answered twice in
    one reply ('Correction: ... here is the full answer: {...}', Sonnet 2026-11-04), and a reply
    can be cut off mid-list: take the most complete JSON object (the later one on a tie), else
    the finished entries of a cut-off one."""
    best, dec = {}, json.JSONDecoder()
    for i, ch in enumerate(text or ""):
        if ch != "{":
            continue
        try:
            obj, _ = dec.raw_decode(text, i)
        except Exception:
            continue
        if isinstance(obj, dict) and obj and all(str(k).isdigit() for k in obj) and len(obj) >= len(best):
            best = {str(k): v for k, v in obj.items()}
    if best:
        return best
    found = {}
    for m in re.finditer(r'"(\d+)"\s*:\s*\[([^\]\[]*)\]', text or ""):
        try:
            found[m.group(1)] = json.loads("[" + m.group(2) + "]")
        except Exception:
            pass
    return found


