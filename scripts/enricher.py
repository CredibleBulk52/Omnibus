# The comic files already carry the publisher's solicitation text (ComicInfo <Summary>, ~98% of
# books) and the creators. Descriptions are written from these, so a new series that Comic Vine
# has not described yet still gets an accurate premise instead of one written from memory.

def _xml_text(xml: str, tag: str) -> Optional[str]:
    import html
    m = re.search(rf"<{tag}>(.*?)</{tag}>", xml or "", re.S)
    if not m:
        return None
    text = html.unescape(re.sub(r"<[^>]+>", " ", m.group(1)))
    return re.sub(r"\s+", " ", text).strip() or None


def _clean_solicit(text: str) -> str:
    # Drop the shouting headline(s) at the start ("THE ROGUES PRESS THE ATTACK!") and the cover /
    # on-sale credits at the end; put back spaces the files lose between sentences ("chase.And").
    out = re.sub(r"([.!?])(?=[A-Z\"“])", r"\1 ", text)
    out = re.sub(r"^(?:[^a-z]{6,}?[!?.]+\s*)+", "", out)
    out = re.split(r"\b(?:Main cover|Variant cover|Cover by|Covers by|Incentive cover|ON SALE|On sale)\b", out)[0]
    return out.strip() or text.strip()


def library_sources(folder_paths: List[str], max_issues: int = 7) -> Tuple[List[Tuple[str, str]], Dict[str, str]]:
    """Solicitation text spread across the whole series (the opening issues for the premise, later
    ones for its scope) and the first issue's creators,
    from the books Omnibus has scanned in the series folder."""
    try:
        conn = sqlite3.connect(f"file:{os.environ.get('DB_PATH', '/appdata/omnibus.db')}?mode=ro", uri=True, timeout=5)
    except Exception:
        return [], {}
    try:
        books = []
        for folder in [f for f in folder_paths if f]:
            row = conn.execute("SELECT id FROM scanned_series WHERE path = ?", (folder.rstrip("/"),)).fetchone()
            if row:
                books = conn.execute(
                    "SELECT issue_number, comicinfo, title FROM scanned_books WHERE series_id = ? ORDER BY sort_order", (row[0],)
                ).fetchall()
                break
    except Exception:
        return [], {}
    finally:
        conn.close()
    with_text = [(num, ci, _xml_text(ci, "Summary")) for num, ci, _ in books if ci]
    with_text = [(num, ci, txt) for num, ci, txt in with_text if txt and len(txt) > 40]
    if not with_text:
        return [], {}
    # The whole run, not just the start (user 2026-10-28: descriptions read like a recap of
    # issues #1-4): the first two issues for the premise, then issues spread evenly to the latest.
    n = len(with_text)
    if n <= max_issues:
        picks = list(range(n))
    else:
        rest = max_issues - 2
        picks = sorted(set([0, 1] + [2 + round(k * (n - 3) / (rest - 1)) for k in range(rest)]))
    sources = []
    for i in picks:
        num, _, txt = with_text[i]
        cleaned = _clean_solicit(txt)
        if len(cleaned) > 40:
            when = "opening issue" if i < 2 else "later issue"
            sources.append((f"Issue #{num or '?'} solicitation, {when}", cleaned[:700]))
    # Story-arc titles are not sent (2026-10-28): they are evocative, not literal ("In Gorilla City"
    # has no Gorilla City, "The War of the Flashes" no war of Flashes) and the AI turned them into events.
    first_ci = with_text[0][1]
    creators = {}
    for role, tag in (("writer", "Writer"), ("artist", "Penciller")):
        names = [n.strip() for n in (_xml_text(first_ci, tag) or "").split(",") if n.strip()]
        if names:
            creators[role] = ", ".join(dict.fromkeys(names))
    return sources, creators


