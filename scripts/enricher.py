class SeriesJsonParser:
    def read(self, path: str) -> Optional[SeriesJson]:
        try:
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f)
            m = data.get("metadata", {})

            def clean(v):
                return None if v in ("None", "null", None) else v

            series = SeriesJson(version=data.get("version", "1.0.2"))
            series.metadata = SeriesMetadata(
                type=m.get("type", "comicSeries"),
                publisher=clean(m.get("publisher")), imprint=clean(m.get("imprint")),
                name=m.get("name"), comicid=m.get("comicid"), year=m.get("year"),
                description_text=m.get("description_text"),
                description_formatted=m.get("description_formatted"),
                volume=m.get("volume"), booktype=m.get("booktype"),
                age_rating=clean(m.get("age_rating")), collects=clean(m.get("collects")),
                comic_image=m.get("comic_image"), total_issues=m.get("total_issues"),
                publication_run=m.get("publication_run"), status=m.get("status"),
                era=clean(m.get("era")), characters=m.get("characters"),
                teams=m.get("teams"), genres=m.get("genres"),
                reading_direction=m.get("reading_direction"),
                enrichment=m.get("enrichment"),
            )
            return series
        except Exception as e:
            print(f"  Error reading {path}: {e}", file=sys.stderr)
            return None

    def write(self, path: str, series: SeriesJson) -> bool:
        try:
            if os.path.exists(path) and not os.path.exists(path + ".bak"):
                shutil.copy2(path, path + ".bak")
            with open(path, "w", encoding="utf-8") as f:
                json.dump(series.to_dict(), f, indent=2, ensure_ascii=False)
            return True
        except Exception as e:
            print(f"  Error writing {path}: {e}", file=sys.stderr)
            return False

    def revert(self, path: str) -> bool:
        bak = path + ".bak"
        if not os.path.exists(bak):
            print(f"  No backup: {bak}", file=sys.stderr)
            return False
        try:
            shutil.copy2(bak, path)
            os.remove(bak)
            print(f"  Reverted: {path}")
            return True
        except Exception as e:
            print(f"  Revert failed: {e}", file=sys.stderr)
            return False


