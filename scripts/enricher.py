class EraDetector:
    AUTO_IMPRINTS = {
        "vertigo": "Vertigo", "black label": "Black Label", "dc black label": "Black Label",
        "elseworlds": "Elseworlds", "wildstorm": "WildStorm", "milestone": "Milestone",
        "marvel max": "MAX", "max comics": "MAX", "ultimate marvel": "Ultimate",
        "ultimate comics": "Ultimate", "marvel knights": "Marvel Knights",
        "icon": "Icon", "epic comics": "Epic", "star wars": "Star Wars",
        "dc absolute": "DC Absolute", "sandman universe": "Sandman Universe",
        "young animal": "Young Animal", "hill house comics": "Hill House Comics",
        "wonder comics": "Wonder Comics", "amalgam": "Amalgam",
    }

    def __init__(self, publishers: List[Dict]):
        self.publishers = publishers

    def detect(self, folder_path: str, series_year: Optional[int] = None) -> Tuple[Optional[str], Optional[str], Optional[str], bool]:
        """Returns (publisher_name, era, imprint, should_skip)."""
        folder_lower = folder_path.lower().replace("\\", "/")

        for pub in self.publishers:
            pub_name = pub.get("publisher", "")
            pub_lower = pub_name.lower()

            if pub_lower not in folder_lower and pub_lower.replace(" ", "") not in folder_lower.replace(" ", ""):
                continue

            # Skip patterns
            for pattern in pub.get("skip_patterns", []):
                if pattern.lower() in folder_lower:
                    return pub_name, None, None, True

            # Era detection
            era = None
            use_folder = pub.get("use_folder_detection", False)

            if use_folder:
                for era_cfg in pub.get("eras", []):
                    # Prefer explicit folder field, fall back to era name
                    folder = era_cfg.get("folder") or era_cfg.get("name", "")
                    if folder and folder.lower() in folder_lower:
                        era = era_cfg.get("name")
                        break

            if not era and series_year:
                for era_cfg in pub.get("eras", []):
                    start = era_cfg.get("start_year")
                    end = era_cfg.get("end_year")
                    if start is None and end is None:
                        continue
                    if (start is None or series_year >= start) and (end is None or series_year <= end):
                        era = era_cfg.get("name")
                        break

            # Imprint detection
            imprint = None
            for imp in pub.get("imprints", []):
                pattern = imp.get("pattern", "").lower()
                if pattern and pattern in folder_lower:
                    imprint = imp.get("name")
                    break

            if not imprint:
                for pattern, name in self.AUTO_IMPRINTS.items():
                    if pattern in folder_lower:
                        imprint = name
                        break

            return pub_name, era, imprint, False

        # Auto-detect publisher from path
        publisher = None
        if "dc comics" in folder_lower or "dc universe" in folder_lower:
            publisher = "DC Comics"
        elif "marvel" in folder_lower:
            publisher = "Marvel"
        elif "image" in folder_lower:
            publisher = "Image Comics"
        elif "dark horse" in folder_lower:
            publisher = "Dark Horse Comics"
        elif "vertigo" in folder_lower:
            publisher = "DC Comics"

        imprint = None
        for pattern, name in self.AUTO_IMPRINTS.items():
            if pattern in folder_lower:
                imprint = name
                break

        return publisher, None, imprint, False


