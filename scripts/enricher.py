    def genres_for_many(self, metas: List[Dict[str, Any]]) -> List[List[str]]:
        """Genres for up to ~20 series in one call (genre retag, 2026-11-03), from what their
        series.json already holds. One list per series, in order; [] where there is no usable answer."""
        system = ("You sort comic series into genres for a library's Genre filter. Genres (use only these names, "
                  "exactly as written):\n" + genre_guide() + "\n\n"
                  f"Give each series 1 to {GENRE_LIMIT} genres, the most defining first. Include every genre a reader browsing the Genre filter would expect to find the series under; leaving one out hides the series from that reader. Most series fit 2 to 4. Do not add a genre for a single story, a guest appearance or a minor element. Use what you know about each series as well as the details given: descriptions are often short or missing. An imprint such as Elseworlds, What If, Ultimate or Absolute marks a series set outside the main continuity. "
                  'Reply with JSON only, one entry per series number, e.g. {"1": ["Superhero", "Team"], "2": ["Horror"]}. '
                  'Write the JSON once, with no commentary or corrections before or after it.')
        lines = []
        for n, m in enumerate(metas, 1):
            chars = ", ".join(str(c) for c in (m.get("characters") or [])[:5])
            desc = re.sub(r"<[^>]+>", " ", str(m.get("description_text") or m.get("description_formatted") or ""))
            desc = re.sub(r"\s+", " ", desc).strip()[:600]   # 600 since 2026-11-04 (was 300)
            lines.append(f"{n}. {m.get('name') or '?'} ({m.get('year') or '?'}), {m.get('publisher') or 'unknown publisher'}"
                         + (f", imprint {m.get('imprint')}" if m.get('imprint') else "")
                         + (f". Characters: {chars}" if chars else "") + (f". About: {desc}" if desc else ""))
        text = None
        budget = 60 * len(metas) + 600
        for attempt in (1, 2, 3):
            self.last_job = None
            try:
                text = self._ask("\n".join(lines), system=system, max_tokens=budget, timeout=120, thinking_off=True)
                if getattr(AnthropicClient, "last_stop", None) == "max_tokens" and attempt < 3 and len(parse_genre_reply(text)) < len(metas):
                    set_ai_job_outcome(self.last_job, "cut_off", f"reply cut off at {budget} tokens")
                    budget *= 3   # cut off mid-list: once more with room (2026-11-04)
                    continue
                break
            except ValueError as e:   # answered, but no usable text (all thinking, cut off): once more with room
                set_ai_job_outcome(self.last_job, "cut_off", str(e))
                self.problem = f"AI reply had no answer: {e}"
                if attempt == 3:
                    break
                budget *= 3
            except Exception as e:
                self.problem = f"AI request failed: {e}"
                if attempt == 1:
                    time.sleep(10)
                else:
                    break
        if text is None:
            return [[] for _ in metas]
        parsed = parse_genre_reply(text)
        if not parsed:
            set_ai_job_outcome(self.last_job, "bad_json", f"genres for 0 of {len(metas)} series")
            self.problem = "AI reply was not the expected list: " + text[:300].replace("\n", " ")
            return [[] for _ in metas]
        out = [allowed_genres(parsed.get(str(n)) or []) for n in range(1, len(metas) + 1)]
        got = sum(1 for g in out if g)
        set_ai_job_outcome(self.last_job, "written" if got else "no_match", f"genres for {got} of {len(metas)} series")
        return out

    @staticmethod
    def is_inadequate(desc: Optional[str]) -> bool:
        if not desc or len(desc) < 50:
            return True
        dl = desc.lower()
        if any(p in dl for p in ["issue mini-series", "issue limited series", "ongoing series",
                                   "one-shot", "-issue series"]):
            return True
        indicators = ["preceded by", "succeeded by", "continued in", "continued from",
                      "notable characters featured", "issues filed under", "(tot "]
        if sum(1 for i in indicators if i in dl) >= 2:
            return True
        if len(re.findall(r'#\d+(?:-\d+)?', desc)) > 5:
            return True
        if re.search(r':\s*#\d+', desc):
            return True
        return False


